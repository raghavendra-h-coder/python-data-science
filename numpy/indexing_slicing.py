import numpy as np

# Create a sample array of student marks
student_marks = np.array([65, 72, 81, 90, 95])

# Access the first student's marks
print(student_marks[0])

# Access the last student's marks
print(student_marks[-1])

# Print the first three marks
print(student_marks[:3])

# Reverse the array
print(student_marks[::-1])